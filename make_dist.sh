#!/bin/bash
#
# Assemble the itch.io download directory.
#
# Two downloads come out of this, and both matter:
#
#   * the APK the game is played from; and
#   * the corresponding source.  OpenTTD is GPLv2, so everyone who downloads the
#     APK is entitled to the source it was built from -- including the Android
#     changes.  Shipping a binary without it is the one thing that would make
#     this distribution improper.
#
# The source is published two ways because they serve different people: a
# complete tarball that stands on its own, and a patch against the exact
# upstream commit, which is a few kilobytes and shows a reviewer at a glance
# exactly what was changed.
set -euo pipefail

BUILD=/root/build
DIST=$BUILD/dist
SRC=$BUILD/openttd
# The exact upstream commit this tree was checked out at, and the only file
# list the patch touches as a result: CMakeLists.txt, src/os/unix/unix.cpp, the
# new cmake/Android.cmake and the new src/os/android/ directory.  Pinning the
# commit is what keeps the patch down to those four, instead of filling up with
# unrelated upstream work.
UPSTREAM_BASE=787ded77135881e518533fb07c97dd31a6e225f8
UPSTREAM_URL=https://github.com/OpenTTD/OpenTTD
UPSTREAM_BASE_DIR=/tmp/base/OpenTTD-$UPSTREAM_BASE

rm -rf "$DIST/downloads"
mkdir -p "$DIST/downloads"

APK_NAME=OpenTTD-16.0-android.apk

echo "== copying the APK"
cp "$BUILD/apk/$APK_NAME" "$DIST/downloads/$APK_NAME"

echo "== staging the Android packaging into the source tree"
# The Android platform layer is a mix of engine edits (cmake/, src/) that live
# in the tree and packaging files (the app manifest, the Java activity, the
# resources, and the build scripts) that live alongside it in $BUILD.  Both have
# to ship for the source to build the APK, so copy the packaging into the tree
# under their in-repo paths before archiving.  Only the source inputs go in;
# the build outputs in apk/out, apk/assets and apk/lib are excluded.
rm -rf "$SRC/apk"
mkdir -p "$SRC/apk/java/org/openttd/android"
cp "$BUILD/apk/AndroidManifest.xml" "$SRC/apk/AndroidManifest.xml"
cp -r "$BUILD/apk/res"               "$SRC/apk/res"
cp "$BUILD/apk/java/org/openttd/android/OpenTTD.java" \
   "$SRC/apk/java/org/openttd/android/OpenTTD.java"
for script in assemble_apk.sh stage_assets.sh verify_apk.sh make_dist.sh; do
    cp "$BUILD/$script" "$SRC/$script"
done
if [ -f /root/scripts/build_deps.sh ]; then
    cp /root/scripts/build_deps.sh "$SRC/build_deps.sh"
fi

echo "== building the source tarball"
# The tree as it was compiled, minus everything that is generated by building.
# tar is given the exclude list rather than being pointed at a pre-cleaned copy
# so that nothing in the tree is modified to produce the archive.
tar czf "$DIST/downloads/OpenTTD-16.0-android-source.tar.gz" \
    -C "$BUILD" \
    --exclude='openttd/build/' \
    --exclude='openttd/build-armv7/' \
    --exclude='openttd/.git' \
    --exclude='openttd/apk/out' \
    --exclude='openttd/apk/assets' \
    --exclude='openttd/apk/lib' \
    --exclude='openttd/apk/*.apk' \
    --exclude='openttd/apk/*.idsig' \
    --exclude='*.o' \
    --exclude='*.pch' \
    openttd

echo "== building the patch"
# A context diff against the upstream commit the tree is based on.  Only files
# this port actually touched appear; --exclude files is not needed because the
# base is exact.
PATCHDIR=$DIST/downloads
diff -ruN "$UPSTREAM_BASE_DIR" "$SRC" > "$PATCHDIR/0001-android-port.patch" || true
# Rewrite the absolute paths diff invented into the a/ b/ form that `patch -p1`
# expects, and drop the hunks that are only upstream drift between the target
# commit and whatever the tree was checked out at.
sed -i "s|^--- $UPSTREAM_BASE_DIR/|--- a/|; s|^+++ $SRC/|+++ b/|" \
    "$PATCHDIR/0001-android-port.patch"

echo "== licences alongside the downloads"
mkdir -p "$DIST/downloads/licenses"
cp "$SRC/COPYING.md"  "$DIST/downloads/licenses/OpenTTD-COPYING.md"
cp "$SRC/CREDITS.md"  "$DIST/downloads/licenses/CREDITS.md"
SETS=/root/downloads/basesets/x
cp "$SETS"/opengfx-7.1/opengfx-7.1/license.txt    "$DIST/downloads/licenses/OpenGFX-license.txt"
cp "$SETS"/opengfx-7.1/opengfx-7.1/readme.txt     "$DIST/downloads/licenses/OpenGFX-readme.txt"
cp "$SETS"/opensfx-1.0.3/opensfx-1.0.3/license.txt "$DIST/downloads/licenses/OpenSFX-license.txt"
cp "$SETS"/opensfx-1.0.3/opensfx-1.0.3/readme.txt  "$DIST/downloads/licenses/OpenSFX-readme.txt"
cp "$SETS"/openmsx-0.4.2/openmsx-0.4.2/license.txt "$DIST/downloads/licenses/OpenMSX-license.txt"
cp "$SETS"/openmsx-0.4.2/openmsx-0.4.2/readme.txt  "$DIST/downloads/licenses/OpenMSX-readme.txt"

echo "== checksums"
( cd "$DIST/downloads" && sha256sum "$APK_NAME" OpenTTD-16.0-android-source.tar.gz \
    0001-android-port.patch > SHA256SUMS.txt )

echo
ls -la "$DIST/downloads"

#!/bin/bash
#
# Lay out everything that ships inside the APK, under apk/assets/game/.
#
# The layout mirrors the directory names OpenTTD searches in its personal
# directory, so the activity unpacks these straight into the app's home and the
# game finds them through its ordinary search path -- no path is configured or
# passed on the command line.
#
# Only freely licensed data goes in here.  The original Transport Tycoon
# Deluxe graphics, sounds and music may not be redistributed, so the free
# replacements (OpenGFX, OpenSFX, OpenMSX) are used instead; the orig_* files
# that remain are metadata describing the original sets, which the player can
# supply from their own copy if they have one.
set -euo pipefail

BUILD=/root/build
GAME=$BUILD/apk/assets/game
BASE=$BUILD/android/baseset
LANGDIR=$BUILD/android/lang
SETS=/root/downloads/basesets/x

rm -rf "$GAME"
mkdir -p "$GAME"/{baseset,langs,lang,ai,game,docs}

echo "== OpenTTD's own base set: graphics, fonts, title screen and metadata"
# openttd.grf (extra graphics), orig_extra.grf and opntitle.dat are generated by
# the build; the fonts and the orig_* set descriptions are copied by it.
for f in openttd.grf orig_extra.grf opntitle.dat openttd.32.bmp \
         OpenTTD-Sans.ttf OpenTTD-Serif.ttf OpenTTD-Small.ttf OpenTTD-Mono.ttf \
         orig_dos.obg orig_dos_de.obg orig_win.obg \
         orig_dos.obm orig_win.obm orig_tto.obm \
         orig_dos.obs orig_win.obs no_music.obm no_sound.obs; do
    cp "$BASE/$f" "$GAME/baseset/"
done

echo "== OpenGFX (or the game has no graphics at all)"
cp "$SETS"/opengfx-8.0/opengfx-8.0/opengfx.obg "$GAME/baseset/"
cp "$SETS"/opengfx-8.0/opengfx-8.0/*.grf         "$GAME/baseset/"

echo "== OpenSFX (sound effects)"
cp "$SETS"/opensfx-1.0.3/opensfx-1.0.3/opensfx.obs "$GAME/baseset/"
cp "$SETS"/opensfx-1.0.3/opensfx-1.0.3/opensfx.cat "$GAME/baseset/"

echo "== OpenMSX (music)"
cp "$SETS"/openmsx-0.4.2/openmsx-0.4.2/openmsx.obm "$GAME/baseset/"
cp "$SETS"/openmsx-0.4.2/openmsx-0.4.2/*.mid        "$GAME/baseset/"

echo "== translations"
# The game looks in "langs" (with the installer's separate download) and in
# "lang"; both are searched, so the files are placed where the base install
# keeps them.
cp "$LANGDIR"/*.lng "$GAME/langs/"
cp "$LANGDIR"/*.lng "$GAME/lang/"

echo "== base graphics and scripts that ship alongside the game"
cp "$BUILD/openttd/bin/ai"/*.nut   "$GAME/ai/"
cp "$BUILD/openttd/bin/game"/*.nut "$GAME/game/"

echo "== licences and provenance"
cp "$BUILD/openttd/COPYING.md"  "$GAME/docs/COPYING.md"
cp "$BUILD/openttd/README.md"   "$GAME/docs/README.md"
cp "$BUILD/openttd/CREDITS.md"  "$GAME/docs/CREDITS.md"
cp "$SETS"/opengfx-8.0/opengfx-8.0/license.txt    "$GAME/docs/OpenGFX-license.txt"
cp "$SETS"/opengfx-8.0/opengfx-8.0/readme.txt     "$GAME/docs/OpenGFX-readme.txt"
cp "$SETS"/opensfx-1.0.3/opensfx-1.0.3/license.txt "$GAME/docs/OpenSFX-license.txt"
cp "$SETS"/opensfx-1.0.3/opensfx-1.0.3/readme.txt  "$GAME/docs/OpenSFX-readme.txt"
cp "$SETS"/openmsx-0.4.2/openmsx-0.4.2/license.txt "$GAME/docs/OpenMSX-license.txt"
cp "$SETS"/openmsx-0.4.2/openmsx-0.4.2/readme.txt  "$GAME/docs/OpenMSX-readme.txt"

echo "== manifest and fingerprint"
# The activity reads this list to know what to unpack, and the fingerprint to
# decide whether a previous unpack is still current.
( cd "$GAME" && find . -type f ! -name manifest.txt ! -name data-version.txt \
    | sed 's|^\./||' | LC_ALL=C sort ) > "$GAME/manifest.txt"

{
    echo "openttd 16.0"
    echo "opengfx 7.1"
    echo "opensfx 1.0.3"
    echo "openmsx 0.4.2"
    echo "langs $(ls "$LANGDIR" | wc -l)"
} | sha256sum | cut -d' ' -f1 > "$GAME/data-version.txt"

echo
echo "staged: $(find "$GAME" -type f | wc -l) files, $(du -sh "$GAME" | cut -f1)"
du -sh "$GAME"/* | sort -h
